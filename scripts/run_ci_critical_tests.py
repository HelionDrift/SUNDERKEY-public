VERSION_ASSERTION = re.compile(
    r'self\.assertEqual\(project(?:\["project"\])?\["version"\],\s*"([^"]+)"\)'
)


def check_release_version_assertions() -> bool:
    project = tomllib.loads((ROOT / "pyproject.toml").read_text(encoding="utf-8"))
    current_version = project["project"]["version"]
    pinned = [
        (path, match.group(1))
        for path in TESTS_DIRECTORY.glob("test_*.py")
        for match in VERSION_ASSERTION.finditer(path.read_text(encoding="utf-8"))
    ]
    if not pinned:
        print("No release-version assertions were found", file=sys.stderr)
        return False
    stale = [(path, version) for path, version in pinned if version != current_version]
    if stale:
        for path, version in stale:
            print(
                f"Stale release-version assertion: {path.relative_to(ROOT)} "
                f"pins {version}, project is {current_version}",
                file=sys.stderr,
            )
        return False
    print(f"Checked {len(pinned)} release-version assertions", flush=True)
    return True


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check-manifest", action="store_true")
    args = parser.parse_args()
    sys.path.insert(0, str(ROOT))
    if not check_release_version_assertions():
        return 1
    missing = sorted(
        test_id
        for test_id in (*CORE_TESTS, *OFFLINE_COMPONENT_TESTS)
        if not (TESTS_DIRECTORY / f"{test_id.split('.')[2]}.py").is_file()
    )
    if missing:
        print(f"Required critical tests are missing: {', '.join(missing)}", file=sys.stderr)
        return 1
    tests = list(CORE_TESTS)
    tests.extend(
        test_id for filename, test_id in OPTIONAL_TESTS if (TESTS_DIRECTORY / filename).is_file()
    )
    tests.extend(OFFLINE_COMPONENT_TESTS)
    if len(set(tests)) != len(tests):
        print("Critical test manifest contains duplicate selectors", file=sys.stderr)
        return 1
    if args.check_manifest:
        from scripts.run_ci_test_shard import CiShardError, discover_cases

        try:
            discovered = {f"tests.{case.id()}" for case in discover_cases()}
        except CiShardError as exc:
            print(f"Complete suite discovery failed: {exc}", file=sys.stderr)
            return 1
        absent = sorted(set(tests) - discovered)
        if absent:
            print(
                "Critical selectors missing from complete shards: " + ", ".join(absent),
                file=sys.stderr,
            )
            return 1
        print(
            f"Checked {len(tests)} critical selectors in complete shard discovery",
            flush=True,
        )
        return 0
    print(f"Running {len(tests)} critical tests: {', '.join(tests)}", flush=True)
    suite = unittest.defaultTestLoader.loadTestsFromNames(tests)
    return 0 if unittest.TextTestRunner(verbosity=1).run(suite).wasSuccessful() else 1


if __name__ == "__main__":
    raise SystemExit(main())
